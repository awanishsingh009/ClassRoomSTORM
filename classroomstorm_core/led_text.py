def glyph_to_16x16(character: str) -> np.ndarray:
    key = (character or " ").upper()
    if key not in GLYPHS_5X7:
        raise ValueError(f"Unsupported LED text character: {character!r}")
    base = np.array([[1 if bit == "1" else 0 for bit in row] for row in GLYPHS_5X7[key]], dtype=np.uint8)
    scaled = np.kron(base, np.ones((2, 2), dtype=np.uint8))
    cell = np.zeros((CELL_SIZE, CELL_SIZE), dtype=np.uint8)
    y0 = (CELL_SIZE - scaled.shape[0]) // 2
    x0 = (CELL_SIZE - scaled.shape[1]) // 2
    cell[y0:y0 + scaled.shape[0], x0:x0 + scaled.shape[1]] = scaled
    return cell


def text_to_led_mask(text: str) -> np.ndarray:
    content = text or "ABBE"
    cells = [glyph_to_16x16(ch) for ch in content.upper()]
    if not cells:
        cells = [glyph_to_16x16(" ")]
    return np.concatenate(cells, axis=1).astype(np.uint8)
